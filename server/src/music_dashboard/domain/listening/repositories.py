from collections.abc import Iterable
from contextlib import AbstractContextManager
from datetime import datetime
from typing import Any, Protocol

from music_dashboard.domain.listening.entities import RawListen


class ListeningRepository(Protocol):
    """MSID identity is stable across metadata remaps; never collapse timestamp ties."""

    def upsert(self, listens: Iterable[RawListen]) -> int: ...
    def quarantine(self, payload: dict[str, object], reason: str, provenance: str) -> None: ...


class SyncStateRepository(Protocol):
    """Implementations own transactions, advisory locking and durable checkpoints."""

    def try_lock(self, user: str) -> bool: ...
    def load_checkpoint(self, user: str) -> dict[str, object]: ...
    def save_checkpoint(self, user: str, checkpoint: dict[str, object]) -> None: ...


class SyncRepositoryPort(Protocol):
    """Durable per-user runs. The advisory lock spans committed page transactions."""

    def locked(self, user: str) -> AbstractContextManager[bool]: ...
    def load_checkpoint(self, user: str) -> dict[str, Any]: ...
    def save_checkpoint(self, user: str, checkpoint: dict[str, Any]) -> None: ...
    def begin_run(self, user: str, kind: str, stats: dict[str, Any] | None = None) -> int: ...
    def load_scan(self, user: str) -> dict[str, Any] | None: ...
    def finish_run(
        self, run_id: int, status: str, stats: dict[str, Any], error: str | None = None
    ) -> None: ...
    def ingest(
        self, user: str, payloads: list[dict[str, Any]], source: str, received_at: datetime
    ) -> int: ...
    def activate_snapshot(
        self,
        user: str,
        rows: Iterable[dict[str, Any]],
        snapshot_at: datetime,
        allow_large_delete: bool = False,
        snapshot_complete: bool = False,
    ) -> dict[str, int]: ...
    def next_retry(self, user: str, kind: str | None = None) -> datetime | None: ...
